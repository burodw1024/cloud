"""Build self-contained ExecuteScript files; no extra JAR, Python or JWT package in NiFi."""
from pathlib import Path


def build(root=None):
    root = Path(root) if root else Path(__file__).resolve().parent
    core = (root/'SignedLoanScope.groovy').read_text()
    for name, wrapper in [('verify-loan-access.groovy', 'verify-body.groovy'),
                          ('attach-loan-receipt.groovy', 'receipt-body.groovy')]:
        (root/name).write_text('// Generated by build_scripts.py; edit the core/wrapper sources.\n' + core + '\n' + (root/wrapper).read_text())


if __name__ == '__main__':
    build()
